import type { Metadata } from "next";
import { Geist, Geist_Mono } from "next/font/google";
import "./globals.css";

import Header from "../components/Header";
import Footer from "../components/Footer";
import Sidebar from "../components/Sidebar";
import Main from "../components/Main";

const geistSans = Geist({
  variable: "--font-geist-sans",
  subsets: ["latin"],
});

const geistMono = Geist_Mono({
  variable: "--font-geist-mono",
  subsets: ["latin"],
});

export const metadata: Metadata = {
  title: "Create Next App",
  description: "Generated by create next app",
};

export default async function RootLayout({
  children,
}: Readonly<{
  children: React.ReactNode;
}>) {
  let sidebarData = "";
  let mainData = "";

  try {
    const [sidebarRes, mainRes] = await Promise.all([
      fetch("http://localhost:2000/p/getSideBarData?collectionId=DMpXizA8GSFb", {
        cache: "no-store",
      }),
      fetch("http://localhost:2000/p/getPublishedDataByPath?collectionId=DMpXizA8GSFb", {
        cache: "no-store",
      }),
    ]);

    const sidebarDataJson = await sidebarRes.json();
    const mainDataJson = await mainRes.json();

    if (!sidebarRes.ok || !mainRes.ok) {
      throw new Error("One or more API requests failed.");
    }

    [sidebarData, mainData] = await Promise.all([sidebarRes.text(), mainRes.text()]);
  } catch (err) {
    // Automatically throws to error.tsx
    console.error("💥 Layout fetch failed:", err);
    throw new Error("Unable to load application data.");
  }

  return (
    <html lang="en">
      <body className={`${geistSans.variable} ${geistMono.variable} antialiased`}>
        <Header />
        <div style={{ display: "flex", minHeight: "80vh" }}>
          <Sidebar data={sidebarData} />
          <Main data={mainData} />
        </div>
        <Footer />
      </body>
    </html>
  );
}
